        async function saveAIAndTraditionalQuality() {
            const moisture = document.getElementById('moistureContent').value;
            const impurities = document.getElementById('impurities').value;
            const foreignMatter = document.getElementById('foreignMatter').value;
            const status = document.getElementById('qualityStatus').value;
            const remarks = document.getElementById('qualityRemarks').value;
            const sampleWeight = parseFloat(document.getElementById('aiSampleWeightInput').value) || 2.0;

            if (!moisture || !impurities || !foreignMatter || !status) {
                showNotification('Error', 'Please fill all traditional quality parameters');
                return;
            }

            const token = activeQualityToken;
            const tokenData = queueData.find(q => q.token === token);

            // Capture annotated canvas snapshot if available
            let annotatedDataUrl = null;
            const canvasEl = document.getElementById('aiDetectionCanvas');
            const imgEl = document.getElementById('aiResultImage');
            if (canvasEl && imgEl && imgEl.complete) {
                const combined = document.createElement('canvas');
                combined.width = canvasEl.width;
                combined.height = canvasEl.height;
                const ctx = combined.getContext('2d');
                ctx.drawImage(imgEl, 0, 0, combined.width, combined.height);
                ctx.drawImage(canvasEl, 0, 0);
                annotatedDataUrl = combined.toDataURL('image/jpeg', 0.85);
            }

            let responseData = null;

            try {
                const res = await fetch(`/api/procurement/${token}/quality/ai/verify`, {
                    method: 'POST',
                    headers: {
                        'Content-Type': 'application/json',
                        'Authorization': 'Bearer ' + (localStorage.getItem('token') || 'demo_token')
                    },
                    body: JSON.stringify({
                        token,
                        detections: currentAiDetections,
                        moisture,
                        impurities,
                        foreignMatter,
                        status,
                        remarks,
                        sampleWeight,
                        annotatedImageData: annotatedDataUrl
                    })
                });
                if (res.ok) responseData = await res.json();
            } catch (err) {
                console.warn('[AI Verify] Network request failed, updating local state:', err);
            }

            // Update in-memory token state
            const metrics = calculateClientQualityMetrics(currentAiDetections);
            if (tokenData) {
                tokenData.qualityVerified = true;
                tokenData.qualityStatus = status;
                tokenData.quality = {
                    moisture,
                    impurities,
                    foreignMatter,
                    status,
                    remarks,
                    sampleWeight,
                    checkedAt: new Date(),
                    aiAssessment: {
                        enabled: true,
                        status: 'verified',
                        totalDetected: currentAiDetections.length,
                        counts: metrics.counts,
                        percentages: metrics.percentages,
                        detections: currentAiDetections,
                        imageUrl: capturedPhotoDataUrl,
                        annotatedImageUrl: annotatedDataUrl || capturedPhotoDataUrl,
                        reportId: (responseData && responseData.reportId) || `RPT-${token}-${Date.now().toString(36).toUpperCase()}`
                    }
                };
            }

            // Advance pipeline tracker: AI Quality Assessment + Human Verification
            pipelineQualityResult = (status === 'failed') ? 'failed' : 'passed';
            if (currentPipelineStageIndex >= 0 && currentPipelineStageIndex < 7) {
                currentPipelineStageIndex = 6; // Human verification completed, ready for weight
                renderPipeline();
            }

            // Update Farmer Portal view
            const farmerDetailsEl = document.getElementById('qualityDetails');
            if (farmerDetailsEl) {
                farmerDetailsEl.textContent = `Completed: Grade A ${metrics.percentages.gradeA}%, URS ${metrics.percentages.urs}% - ${status.toUpperCase()}`;
            }
            const farmerReportBtn = document.getElementById('farmerViewReportBtn');
            if (farmerReportBtn) farmerReportBtn.style.display = 'inline-block';

            // Enable Digital Quality Report button
            document.getElementById('btnOpenDigitalReport').style.display = 'inline-block';

            showNotification('Quality Saved', `Token ${token}: AI quality & human verification confirmed. Grade A: ${metrics.percentages.gradeA}%, URS: ${metrics.percentages.urs}%`);

            // Hide quality modal and refresh counters
            bootstrap.Modal.getInstance(document.getElementById('qualityModal')).hide();
            stopAICamera();
            refreshDashboard();
        }

