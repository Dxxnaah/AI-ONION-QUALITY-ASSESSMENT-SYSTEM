        async function verifyAadhaarOtp() {
            const cleanAadhaar = document.getElementById('farmerAadhaar').value.replace(/\D/g, '');
            const otpInput = document.getElementById('aadhaarOtpInput');
            const otpVal = (otpInput ? otpInput.value : '').trim();
            const feedback = document.getElementById('otpFeedback');

            if (!otpVal) {
                if (feedback) {
                    feedback.className = 'mt-2 small text-danger';
                    feedback.textContent = 'Please enter the 6-digit OTP received.';
                    feedback.style.display = 'block';
                }
                if (otpInput) otpInput.focus();
                return;
            }

            if (otpVal.length !== 6 || !/^\d{6}$/.test(otpVal)) {
                if (feedback) {
                    feedback.className = 'mt-2 small text-danger';
                    feedback.textContent = 'OTP must be exactly 6 numeric digits.';
                    feedback.style.display = 'block';
                }
                return;
            }

            if (isOtpSessionUsed) {
                if (feedback) {
                    feedback.className = 'mt-2 small text-danger';
                    feedback.textContent = 'This OTP has already been verified and cannot be reused. Please request a new OTP.';
                    feedback.style.display = 'block';
                }
                return;
            }

            if (Date.now() > otpExpiresAt) {
                if (feedback) {
                    feedback.className = 'mt-2 small text-danger';
                    feedback.textContent = 'OTP has expired. Please click "Resend" to get a fresh code.';
                    feedback.style.display = 'block';
                }
                return;
            }

            let result = null;
            try {
                const res = await fetch('/api/otp/verify-aadhaar-otp', {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({ txnId: currentAadhaarTxnId, aadhaar: cleanAadhaar, otp: otpVal })
                });
                result = await res.json();
            } catch (err) {
                console.warn('[Aadhaar OTP] Backend verify endpoint error, evaluating client simulation:', err);
            }

            // Client fallback evaluation if backend not reachable
            if (!result) {
                if (otpVal === localDynamicOtp) {
                    result = { success: true, verified: true, verificationToken: 'vtok_' + Date.now() };
                } else {
                    otpAttemptCount++;
                    const rem = Math.max(0, 3 - otpAttemptCount);
                    result = {
                        success: false,
                        error: rem > 0 ? `Incorrect OTP. ${rem} attempt(s) remaining.` : 'Maximum attempts exceeded. Please request a new OTP.'
                    };
                }
            }

            if (result.success || result.verified) {
                isAadhaarVerified = true;
                verifiedAadhaarNumber = cleanAadhaar;
                aadhaarVerificationToken = result.verificationToken || ('vtok_' + Date.now());
                isOtpSessionUsed = true;

                clearInterval(otpTimerInterval);
                clearInterval(resendCooldownInterval);

                // Lock Aadhaar input to prevent changing without re-verification
                const aadhaarEl = document.getElementById('farmerAadhaar');
                if (aadhaarEl) aadhaarEl.readOnly = true;

                // Hide Send OTP button, show Verified badge, hide OTP container
                const sendBtn = document.getElementById('btnSendAadhaarOtp');
                if (sendBtn) sendBtn.style.display = 'none';

                const verifiedBadge = document.getElementById('aadhaarVerifiedBadge');
                if (verifiedBadge) verifiedBadge.style.display = 'block';

                const otpContainer = document.getElementById('aadhaarOtpContainer');
                if (otpContainer) otpContainer.style.display = 'none';

                showNotification('Aadhaar Verified', 'Aadhaar successfully verified via OTP.');
            } else {
                otpAttemptCount++;
                if (feedback) {
                    feedback.className = 'mt-2 small text-danger';
                    feedback.textContent = result.error || 'Invalid OTP. Please check and try again.';
                    feedback.style.display = 'block';
                }
                showNotification('Verification Failed', result.error || 'Invalid OTP. Please try again.');
            }
        }

