        function drawBoundingBoxes(canvas, img, detections) {
            const ctx = canvas.getContext('2d');
            ctx.clearRect(0, 0, canvas.width, canvas.height);

            const colors = {
                GOOD: '#10b981',
                DAMAGED: '#f59e0b',
                ROTTEN: '#ef4444',
                SPROUTED: '#8b5cf6',
                UNDERSIZED: '#0ea5e9'
            };

            detections.forEach(det => {
                const effectiveClass = (det.humanVerifiedClass || det.class || 'GOOD').toUpperCase();
                const color = colors[effectiveClass] || '#10b981';

                // Bboxes are stored in percentage [0-100]
                const x = (det.bbox.x / 100) * canvas.width;
                const y = (det.bbox.y / 100) * canvas.height;
                const w = (det.bbox.width / 100) * canvas.width;
                const h = (det.bbox.height / 100) * canvas.height;

                // Draw bounding box
                ctx.strokeStyle = color;
                ctx.lineWidth = 2.5;
                ctx.setLineDash(det.humanVerified ? [] : [4, 2]);
                ctx.strokeRect(x, y, w, h);
                ctx.setLineDash([]);

                // Draw label background
                const confPercent = Math.round(det.confidence * 100);
                const reviewTag = (!det.humanVerified && det.needsReview) ? ' ⚠️' : '';
                const labelText = `#${det.id} ${effectiveClass} ${confPercent}%${reviewTag}`;

                ctx.font = 'bold 11px sans-serif';
                const textWidth = ctx.measureText(labelText).width;
                const labelH = 18;
                const labelY = Math.max(0, y - labelH);

                ctx.fillStyle = color;
                ctx.fillRect(x, labelY, textWidth + 10, labelH);

                // Draw label text
                ctx.fillStyle = '#ffffff';
                ctx.fillText(labelText, x + 5, labelY + 13);
            });
        }

