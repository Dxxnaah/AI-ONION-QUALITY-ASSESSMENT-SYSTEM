        // Step 3: Image validation
        function validateCapturedCanvas(canvas) {
            if (!canvas || canvas.width < 320 || canvas.height < 240) {
                return { valid: false, message: 'Image resolution is insufficient. Please capture another image.' };
            }

            try {
                const ctx = canvas.getContext('2d');
                // Sample center region
                const sampleW = Math.min(200, canvas.width);
                const sampleH = Math.min(200, canvas.height);
                const sx = Math.floor((canvas.width - sampleW) / 2);
                const sy = Math.floor((canvas.height - sampleH) / 2);
                const imgData = ctx.getImageData(sx, sy, sampleW, sampleH);
                const data = imgData.data;

                let totalBrightness = 0;
                for (let i = 0; i < data.length; i += 4) {
                    // Perceived luminance
                    totalBrightness += (0.299 * data[i] + 0.587 * data[i+1] + 0.114 * data[i+2]);
                }
                const avgLuminance = totalBrightness / (data.length / 4);

                if (avgLuminance < 25) {
                    return { valid: false, message: 'Image is excessively dark. Please capture with better illumination.' };
                }
                if (avgLuminance > 248) {
                    return { valid: false, message: 'Image is overexposed / washed out. Please adjust lighting and recapture.' };
                }
            } catch (e) {
                console.warn('[Validation] Canvas pixel inspection bypassed:', e);
            }

            return { valid: true };
        }

