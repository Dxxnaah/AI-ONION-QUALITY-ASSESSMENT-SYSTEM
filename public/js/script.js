        // Client Quality Metrics calculation adhering strictly to configured rules
        function calculateClientQualityMetrics(detections) {
            const total = detections.length;
            if (total === 0) {
                return {
                    total: 0,
                    counts: { good: 0, damaged: 0, rotten: 0, sprouted: 0, undersized: 0 },
                    percentages: { good: 0, damaged: 0, rotten: 0, sprouted: 0, undersized: 0, gradeA: 0, urs: 0 },
                    recommendedStatus: 'failed'
                };
            }

            const counts = { good: 0, damaged: 0, rotten: 0, sprouted: 0, undersized: 0 };
            detections.forEach(d => {
                const cls = (d.humanVerifiedClass || d.class || 'GOOD').toLowerCase();
                if (counts[cls] !== undefined) counts[cls]++;
                else counts.good++;
            });

            const percentages = {
                good: Number(((counts.good / total) * 100).toFixed(1)),
                damaged: Number(((counts.damaged / total) * 100).toFixed(1)),
                rotten: Number(((counts.rotten / total) * 100).toFixed(1)),
                sprouted: Number(((counts.sprouted / total) * 100).toFixed(1)),
                undersized: Number(((counts.undersized / total) * 100).toFixed(1))
            };

            // Grade A defect tolerance penalties
            let penalty = 0;
            if (percentages.damaged > clientGradingConfig.gradeA.maxDamaged) penalty += (percentages.damaged - clientGradingConfig.gradeA.maxDamaged);
            if (percentages.rotten > clientGradingConfig.gradeA.maxRotten) penalty += (percentages.rotten * 1.5);
            if (percentages.sprouted > clientGradingConfig.gradeA.maxSprouted) penalty += (percentages.sprouted - clientGradingConfig.gradeA.maxSprouted);
            if (percentages.undersized > clientGradingConfig.gradeA.maxUndersized) penalty += (percentages.undersized - clientGradingConfig.gradeA.maxUndersized);

            percentages.gradeA = Number(Math.max(0, Math.min(100, percentages.good - penalty)).toFixed(1));

            const ursSum = (counts.rotten * clientGradingConfig.urs.rottenFactor) +
                           (counts.damaged * clientGradingConfig.urs.damagedFactor) +
                           (counts.sprouted * clientGradingConfig.urs.sproutedFactor) +
                           (counts.undersized * clientGradingConfig.urs.undersizedFactor);
            percentages.urs = Number(Math.min(100, Math.max(0, (ursSum / total) * 100)).toFixed(1));

            let recommendedStatus = 'passed';
            if (percentages.gradeA < 55.0 || percentages.rotten > 2.0) recommendedStatus = 'failed';
            else if (percentages.gradeA < 75.0) recommendedStatus = 'conditionally_passed';

            return { total, counts, percentages, recommendedStatus };
        }

